def validate_registry(specs):
    """Require every adopted case to register once with the declared metadata."""
    actual = {spec.id: (spec.tier, spec.feature) for spec in specs}
    if len(actual) != len(specs):
        raise ValueError("Duplicate E2E case IDs")
    missing = sorted(EXPECTED_CASES.keys() - actual.keys())
    extra = sorted(actual.keys() - EXPECTED_CASES.keys())
    changed = sorted(key for key in actual.keys() & EXPECTED_CASES.keys()
                     if actual[key] != EXPECTED_CASES[key])
    if missing or extra or changed:
        raise ValueError(
            f"E2E manifest mismatch. Missing: {missing}. Unexpected: {extra}. "
            f"Changed tier or feature: {changed}."
        )


def gate_passed(selected, results, summary):
    """Accept exactly one passing result per selected case and full process evidence."""
    expected = {spec.id for spec in selected}
    observed = {result.id for result in results}
    return (
        bool(expected)
        and len(expected) == len(selected) == len(results)
        and expected == observed
        and all(result.status == "PASS" for result in results)
        and summary["sanitizer_clean"]
        and all(shutdown["clean_exit"] for shutdown in summary["fixture_shutdowns"])
        and summary["aggregated_sanitizers"]["process_count"] == len(summary["fixture_shutdowns"])
        and (bool(summary["fixture_shutdowns"]) or not any(spec.requires_server for spec in selected))
    )
